// JSSource is the script served at [RoutesJS], JSHash a short hash of it
var JSSource, JSHash = jsSource()

// JSURL is [RoutesJS] with [JSHash], so a page can keep the script until a path changes
var JSURL = RoutesJS + "?v=" + JSHash

func jsSource() ([]byte, string) {
	b, err := json.Marshal(JS)
	if err != nil {
		panic(err)
	}
	src := []byte("self.ROUTES = " + string(b) + ";\n")
	sum := sha256.Sum256(src)
	return src, hex.EncodeToString(sum[:8])
}

// URL fills the :params of pattern in order, a string is path-escaped and anything else
// must be a [fmt.Stringer] (pgtype.UUID); it panics on a wrong count, which is a bug in the caller
//
//	URL(ChoreDone, householdID, choreID) == "/h/<householdID>/chores/<choreID>/done"
func URL(pattern string, args ...any) string {
	segs := strings.Split(pattern, "/")
	n := 0
	for i, s := range segs {
		if !strings.HasPrefix(s, ":") {
			continue
		}
		if n == len(args) {
			panic(fmt.Sprintf("routes.URL(%q): %d args, want more", pattern, len(args)))
		}
		var v string
		switch a := args[n].(type) {
		case string:
			v = a
		case fmt.Stringer:
			v = a.String()
		default:
			panic(fmt.Sprintf("routes.URL(%q): arg %d is %T, want string or fmt.Stringer", pattern, n, a))
		}
		segs[i] = url.PathEscape(v)
		n++
	}
	if n != len(args) {
		panic(fmt.Sprintf("routes.URL(%q): %d args, want %d", pattern, len(args), n))
	}
	return strings.Join(segs, "/")
}
